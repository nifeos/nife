//! The trust root: the measurements this kernel image demands of the boot program, and of the table
//! the progenitor measures everything else against. Two sources vouch for each of the two entries,
//! and both must agree. The build hashes the archive entries it packed and `kernel/build.rs`
//! compiles the digests into [`TRUST_ROOT`]. The loader hands the progenitor's digest and the
//! table's (`nife.base`) on the command line ([`record_loader_digests`], §235 (the OS is built and
//! updated from packages), T4 with T2). The boot path calls [`require`] before it enters userspace.
//! It fails closed every way: wrong bytes halt, a missing measurement halts, and a loader that
//! handed no digests halts, because an empty trust root vouches for nothing. See
//! notes/trusted-init.md.

// `TRUST_ROOT`, generated by `kernel/build.rs` from `target/init-measure-<arch>.txt`: the digests of
// the boot programs this kernel image was built against. Empty if the build did not run the
// measurement step, which `require` treats as a refusal.
include!(concat!(env!("OUT_DIR"), "/trust_root.rs"));

use measured_boot::loader_digests::{self, LoaderDigests, Refusal, Word};

/// The digest the trust root demands for the boot program `name`, if it names it.
// Test-only today: the boot path calls `require`, which decides and halts. These two are the same
// decision without the halt, which is what a test can actually assert on.
#[cfg_attr(not(feature = "system_tests"), allow(dead_code))]
pub fn expected(name: &str) -> Option<measured_boot::Digest> {
    measured_boot::expected(TRUST_ROOT, name)
}

/// Measure `bytes` against the trust root's entry for `name`. The decision function, separated from
/// the halt so tests can ask it what it thinks without ending the run.
#[cfg_attr(not(feature = "system_tests"), allow(dead_code))]
pub fn verify(name: &str, bytes: &[u8]) -> Result<(), measured_boot::VerifyError> {
    measured_boot::verify(TRUST_ROOT, name, bytes)
}

/// Measure an archive entry, or halt. Called with the entry's bytes immediately before the kernel
/// builds the progenitor's address space and enters it. Two entries reach it, the boot program and
/// the measurement table ([`require_program_measurements`]), so the diagnostics say entries. A
/// mismatch is not recoverable, since there is no second progenitor: this prints what it expected
/// and measured, loudly, because a silent halt at boot looks like a hardware problem. The progenitor
/// is held to the loader's `nife.progenitor` first, then to the trust root.
pub(crate) fn require(name: &str, bytes: &[u8]) {
    let measured = measured_boot::sha256(bytes);
    if name == crate::user::PROGENITOR_ENTRY {
        require_from_loader(name, Word::Progenitor, &measured);
    }
    match measured_boot::verify_digest(TRUST_ROOT, name, &measured) {
        Ok(()) => {}
        Err(measured_boot::VerifyError::Unmeasured) => {
            crate::println!();
            crate::println!(
                "  MEASURED BOOT REFUSED: no measurement for the archive entry '{name}'"
            );
            crate::println!("    measured sha256 {}", Hex(&measured));
            crate::println!(
                "    this kernel image carries {} measurement(s); it was built without the",
                TRUST_ROOT.len()
            );
            crate::println!("    build's measurement step, so it can vouch for nothing.");
            crate::println!("  halting rather than handing the archive to the progenitor.");
            // The boot thread leaves the scheduler rather than parking on its run queue, so nothing
            // after this runs (`arch::HaltReason`). Every refusal below ends the same way.
            crate::sched::exit();
        }
        Err(measured_boot::VerifyError::Mismatch) => {
            crate::println!();
            crate::println!(
                "  MEASURED BOOT REFUSED: '{name}' is not what this kernel image was built against"
            );
            if let Some(want) = measured_boot::expected(TRUST_ROOT, name) {
                crate::println!("    expected sha256 {}", Hex(&want));
            }
            crate::println!("    measured sha256 {}", Hex(&measured));
            crate::println!("  halting rather than handing the archive to the progenitor.");
            crate::sched::exit();
        }
    }
}

/// Vouch for the table the progenitor measures its own loads against: the kernel's whole part in
/// extending the chain past the progenitor. The loader's `nife.base` names the table, and so does
/// the trust root; the table must match both. The table is an ordinary archive entry,
/// [`measured_boot::PROGRAM_MEASUREMENTS`], because the progenitor cannot carry a table of the
/// archive it is in; the kernel hashes it and neither parses nor acts on it. A missing table halts,
/// for [`require`]'s reason. See notes/trusted-init/chain-past-the-progenitor.md.
pub(crate) fn require_program_measurements(fs: &nifefs::Fs<'_>) {
    let name = measured_boot::PROGRAM_MEASUREMENTS;
    match fs.read(name) {
        Some(bytes) => {
            require_from_loader(name, Word::Base, &measured_boot::sha256(bytes));
            require(name, bytes);
        }
        None => {
            crate::println!();
            crate::println!("  MEASURED BOOT REFUSED: the archive carries no '{name}' table");
            crate::println!(
                "    the progenitor could not vouch for anything it loads, so it is not started."
            );
            crate::println!("  halting rather than entering a progenitor that measures nothing.");
            crate::sched::exit();
        }
    }
}

/// Load one archive program the way the progenitor would: only if the chain vouches for it. A boot
/// that replaces the hand-over with its own workload (soak, job mix, bench, disk throughput) runs
/// the ordinary chain, two links long: the table against this kernel image, then `name` against the
/// table. `None` means the archive, or the boot, has no such program; bytes the table will not
/// vouch for halt with `MEASURED BOOT REFUSED`. See
/// notes/trusted-init/chain-past-the-progenitor.md.
///
/// Name: provisional, minted 2026-09-25 by milestone 563's lane, to sit beside [`require`] and
/// [`require_program_measurements`] as the third member of the family. calef names public
/// functions.
// Called only by the boots that replace the hand-over; an ordinary boot measures through
// `user::boot_progenitor` and never reaches it.
#[cfg_attr(
    not(any(
        feature = "bench",
        feature = "soak_test",
        feature = "job_mix",
        feature = "disk_throughput",
        feature = "network_bench",
        feature = "storage_bench"
    )),
    allow(dead_code)
)]
pub fn require_program(name: &str) -> Option<&'static [u8]> {
    let fs = nifefs::Fs::parse(crate::user::initial_ramdisk()?).ok()?;
    // Halts unless the table is the one this kernel image was built against, so past this line the
    // table's word on `name` is the kernel's word.
    require_program_measurements(&fs);
    let bytes = fs.read(name)?;
    let table = fs
        .read(measured_boot::PROGRAM_MEASUREMENTS)
        .and_then(|t| core::str::from_utf8(t).ok())
        .unwrap_or("");
    match measured_boot::verify_in_manifest(table, name, bytes) {
        Ok(()) => Some(bytes),
        Err(measured_boot::VerifyError::Unmeasured) => {
            crate::println!();
            crate::println!(
                "  MEASURED BOOT REFUSED: the archive's measurement table has no entry for '{name}'"
            );
            crate::println!("  halting rather than entering a program nothing vouches for.");
            crate::sched::exit();
        }
        Err(measured_boot::VerifyError::Mismatch) => {
            crate::println!();
            crate::println!(
                "  MEASURED BOOT REFUSED: '{name}' is not what the archive's measurement table says"
            );
            crate::println!("    measured sha256 {}", Hex(&measured_boot::sha256(bytes)));
            crate::println!("  halting rather than entering a program nothing vouches for.");
            crate::sched::exit();
        }
    }
}

/// What the loader's command line said, recorded once at boot by [`record_loader_digests`]. `None`
/// until then, and on a boot whose loader wrote no command line at all.
static LOADER_DIGESTS: crate::sync::InterruptSafeMutex<Option<Result<LoaderDigests, Refusal>>> =
    crate::sync::InterruptSafeMutex::new(crate::sync::rank::RAM, None);

/// **Record the loader's two digests from the boot command line**, or why it has none: `None` for
/// a boot with no command line. Called once by each front end while the line is still mapped
/// (`memory::initialize` for `/chosen/bootargs`, `arch::x86_64::machine` for the PVH line). It
/// decides nothing; [`require`] refuses at the moment a digest is needed, so a boot that enters no
/// progenitor (a kernel-only test image) never asks.
///
/// Name: provisional, minted 2026-11-01 (UTC) by milestone 695's lane, beside
/// `memory::record_boot_slot`.
pub(crate) fn record_loader_digests(cmdline: Option<&[u8]>) {
    let read = match cmdline {
        None => Err(Refusal::Missing(Word::Progenitor)),
        // Not UTF-8 is read as an empty line: neither key can be found in it.
        Some(bytes) => loader_digests::parse(core::str::from_utf8(bytes).unwrap_or("")),
    };
    *LOADER_DIGESTS.lock() = Some(read);
}

/// Hold `measured`, the entry `name`'s digest, to the loader's `word`, or halt saying which part
/// of the handoff failed.
fn require_from_loader(name: &str, word: Word, measured: &measured_boot::Digest) {
    let recorded = *LOADER_DIGESTS.lock();
    let refusal = match recorded {
        Some(Ok(digests)) => {
            let want = match word {
                Word::Progenitor => digests.progenitor,
                Word::Base => digests.base,
            };
            if want == *measured {
                return;
            }
            crate::println!();
            crate::println!(
                "  MEASURED BOOT REFUSED: '{name}' is not what the loader's {} names",
                word.key()
            );
            crate::println!("    expected sha256 {}", Hex(&want));
            crate::println!("    measured sha256 {}", Hex(measured));
            crate::println!("  halting rather than handing the archive to the progenitor.");
            crate::sched::exit();
        }
        Some(Err(refusal)) => refusal,
        None => Refusal::Missing(word),
    };
    crate::println!();
    match refusal {
        Refusal::Missing(missing) => crate::println!(
            "  MEASURED BOOT REFUSED: the loader handed no {} digest on the command line",
            missing.key()
        ),
        Refusal::Repeated(repeated) => crate::println!(
            "  MEASURED BOOT REFUSED: the command line names {} twice",
            repeated.key()
        ),
        Refusal::Malformed(bad, why) => crate::println!(
            "  MEASURED BOOT REFUSED: the command line's {} is not a digest ({why:?})",
            bad.key()
        ),
    }
    crate::println!("    the archive entry '{name}' has nothing to be measured against.");
    crate::println!("  halting rather than handing the archive to the progenitor.");
    crate::sched::exit();
}

/// A digest as hex, for the diagnostics above. `Display` rather than a helper returning a string,
/// because there is no allocator here and the 64 characters have to live somewhere: they live in
/// this value's own frame while it is being formatted.
struct Hex<'a>(&'a measured_boot::Digest);

impl core::fmt::Display for Hex<'_> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        let text = measured_boot::hex(self.0);
        // `measured_boot::hex` emits only ASCII hex digits, so this cannot fail; the fallback keeps
        // a boot failure's diagnostic printable rather than panicking inside it.
        f.write_str(core::str::from_utf8(&text).unwrap_or("<unprintable>"))
    }
}
