//! Device trees no firmware would write, and what the parser must do with them.
//!
//! Every test here is a regression for a bug that was real. The other two test files parse the
//! trees QEMU hands over; this one holds the parser to blobs a hostile or broken firmware could
//! write, because the blob is the first thing a kernel reads and nothing can check it. Some of
//! the bugs were found by a coverage-guided fuzzer, some by reading the code and some by mutation
//! testing. They run on the host in milliseconds, so inputs that cost real time to find cost
//! nothing to keep.

use device_tree_blob::{DeviceTreeBlob, Error, MAXIMUM_DEPTH, Region};

/// Enough of a device tree to reach the structure block, built from parts.
///
/// The header is 40 bytes of big-endian u32s, then the memory-reservation block (one all-zero entry
/// terminates it), then the structure block, then the strings block. Hand-assembled rather than
/// generated by `dtc`, because the whole point is to write blobs `dtc` would refuse.
struct Blob {
    strings: Vec<u8>,
    structure: Vec<u8>,
}

impl Blob {
    fn new() -> Blob {
        Blob {
            strings: Vec::new(),
            structure: Vec::new(),
        }
    }

    /// Intern a property name and return its offset in the strings block.
    fn string(&mut self, s: &[u8]) -> u32 {
        let at = self.strings.len() as u32;
        self.strings.extend_from_slice(s);
        self.strings.push(0);
        at
    }

    fn token(&mut self, t: u32) -> &mut Self {
        self.structure.extend_from_slice(&t.to_be_bytes());
        self
    }

    /// `FDT_BEGIN_NODE` plus the node's name, NUL-terminated and padded to four bytes.
    fn begin_node(&mut self, name: &[u8]) -> &mut Self {
        self.token(1);
        self.structure.extend_from_slice(name);
        self.structure.push(0);
        while !self.structure.len().is_multiple_of(4) {
            self.structure.push(0);
        }
        self
    }

    fn end_node(&mut self) -> &mut Self {
        self.token(2)
    }

    /// `FDT_PROP`: a length, a name offset, then the value padded to four bytes.
    fn prop(&mut self, name: &[u8], value: &[u8]) -> &mut Self {
        let name_off = self.string(name);
        self.token(3);
        self.structure
            .extend_from_slice(&(value.len() as u32).to_be_bytes());
        self.structure.extend_from_slice(&name_off.to_be_bytes());
        self.structure.extend_from_slice(value);
        while !self.structure.len().is_multiple_of(4) {
            self.structure.push(0);
        }
        self
    }

    fn finish(&mut self) -> Vec<u8> {
        self.finish_with_reservations(&[])
    }

    /// Like [`finish`](Self::finish), with real `/memreserve/` entries ahead of the terminating
    /// all-zero pair. The fixtures' reservation blocks are empty, so this is the only way a test
    /// gets a non-trivial one.
    fn finish_with_reservations(&mut self, rsv: &[(u64, u64)]) -> Vec<u8> {
        self.token(9); // FDT_END

        const HEADER: usize = 40;
        let off_rsvmap = HEADER;
        let off_struct = off_rsvmap + 16 * (rsv.len() + 1); // the all-zero entry terminates the list
        let off_strings = off_struct + self.structure.len();
        let total = off_strings + self.strings.len();

        let mut b = Vec::with_capacity(total);
        for word in [
            0xd00d_feed,
            total as u32,
            off_struct as u32,
            off_strings as u32,
            off_rsvmap as u32,
            17, // version
            16, // last_comp_version
            0,  // boot_cpuid_phys
            self.strings.len() as u32,
            self.structure.len() as u32,
        ] {
            b.extend_from_slice(&word.to_be_bytes());
        }
        for &(start, size) in rsv {
            b.extend_from_slice(&start.to_be_bytes());
            b.extend_from_slice(&size.to_be_bytes());
        }
        b.extend_from_slice(&[0u8; 16]);
        b.extend_from_slice(&self.structure);
        b.extend_from_slice(&self.strings);
        b
    }
}

/// Two big-endian 64-bit cells: the `#address-cells = 2, #size-cells = 2` layout every 64-bit board
/// uses, which is what the fixtures carry and what `decode_reg` sees in practice.
fn reg64(start: u64, size: u64) -> Vec<u8> {
    let mut v = Vec::new();
    v.extend_from_slice(&start.to_be_bytes());
    v.extend_from_slice(&size.to_be_bytes());
    v
}

/// A tree `depth` levels deep whose deepest node is the only one matching `intc`, and which carries
/// a `reg` there. Depth 1 is the root, so `depth = 17` puts the interesting node at 17.
fn nested(depth: usize) -> Vec<u8> {
    let mut b = Blob::new();
    b.begin_node(b"");
    b.prop(b"#address-cells", &2u32.to_be_bytes());
    b.prop(b"#size-cells", &2u32.to_be_bytes());
    for _ in 0..depth - 2 {
        b.begin_node(b"bus");
    }
    b.begin_node(b"intc@8000000");
    b.prop(b"reg", &reg64(0x800_0000, 0x1_0000));
    for _ in 0..depth {
        b.end_node();
    }
    b.finish()
}

/// **A node at the deepest depth is found, and a tree one deeper is refused by every lookup.**
///
/// `node_register_regions` once carried `#address-cells`/`#size-cells` down a 16-entry per-depth array and
/// matched a node at *any* depth >= 2. At depth 17 the `reg` arm read one past the array: an
/// out-of-bounds index, a panic in the parser the kernel runs against a blob it did not write.
/// The guard that fixed it left a node at depth 17 present for two lookups and absent for five.
/// The walk now refuses a tree nested past [`MAXIMUM_DEPTH`] with `TooDeep` for every lookup, so
/// every depth a lookup sees has a slot, and a node at the deepest depth decodes with its parent's
/// cell widths.
#[test]
fn a_node_at_the_deepest_depth_is_found_and_one_deeper_is_refused() {
    let mut out = [Region {
        start: 0,
        size_bytes: 0,
    }; 4];
    let intc = Region {
        start: 0x800_0000,
        size_bytes: 0x1_0000,
    };

    for depth in [3, 16, 17, 40, MAXIMUM_DEPTH] {
        let blob = nested(depth);
        let tree = DeviceTreeBlob::from_bytes(&blob).unwrap();
        assert_eq!(
            tree.node_register_regions(b"intc", &mut out),
            Ok(1),
            "a node at depth {depth} is found"
        );
        assert_eq!(out[0], intc, "and decoded with the root's 2/2 cells");
        assert_eq!(
            tree.node_property(b"intc", b"reg"),
            Ok(Some(&reg64(0x800_0000, 0x1_0000)[..]))
        );
    }

    let blob = nested(MAXIMUM_DEPTH + 1);
    let tree = DeviceTreeBlob::from_bytes(&blob).unwrap();
    let mut values = [None; 1];
    assert_eq!(
        tree.node_register_regions(b"intc", &mut out),
        Err(Error::TooDeep)
    );
    assert_eq!(
        tree.node_register_regions_compatible(b"arm,pl031", &mut out),
        Err(Error::TooDeep)
    );
    assert_eq!(tree.node_property(b"intc", b"reg"), Err(Error::TooDeep));
    assert_eq!(
        tree.node_properties(b"intc", b"reg", &mut values),
        Err(Error::TooDeep)
    );
    assert_eq!(
        tree.node_property_inherited(b"intc", b"reg"),
        Err(Error::TooDeep)
    );
    assert_eq!(
        tree.node_property_compatible(b"arm,pl031", b"reg"),
        Err(Error::TooDeep)
    );
    assert_eq!(tree.pointer_handle_property(1, b"reg"), Err(Error::TooDeep));
    assert_eq!(tree.memory_regions(&mut out), Err(Error::TooDeep));
    assert_eq!(tree.reserved_memory_regions(&mut out), Err(Error::TooDeep));
    assert_eq!(tree.initial_ramdisk(), Err(Error::TooDeep));
    assert_eq!(tree.boot_arguments(), Err(Error::TooDeep));
}

/// **A `reg` pair whose `start + size` wraps is refused, not passed out.**
///
/// Found by the fuzzer. `Region::end()` was a plain `start + size` on two numbers straight out of the
/// blob, and a kernel placing its allocator calls it on every RAM region the device tree declares.
/// Under the dev profile's overflow checks that is a panic on the boot path.
#[test]
fn a_memory_region_that_wraps_the_address_space_is_refused() {
    let mut b = Blob::new();
    b.begin_node(b"");
    b.prop(b"#address-cells", &2u32.to_be_bytes());
    b.prop(b"#size-cells", &2u32.to_be_bytes());
    b.begin_node(b"memory@0");
    b.prop(b"reg", &reg64(u64::MAX, u64::MAX));
    b.end_node();
    b.end_node();
    let blob = b.finish();

    let tree = DeviceTreeBlob::from_bytes(&blob).unwrap();
    let mut out = [Region {
        start: 0,
        size_bytes: 0,
    }; 4];
    assert_eq!(
        tree.memory_regions(&mut out),
        Err(Error::RegionOverflow),
        "a region past the top of the address space is not a region"
    );
}

/// **`Region::end` holds on its own**, whatever built the region.
///
/// The type is `pub` with `pub` fields, so the refusal above is not the only thing standing between
/// a hostile pair and the addition. Saturating is the backstop; the refusal is the check.
#[test]
fn region_end_saturates_rather_than_wrapping() {
    assert_eq!(
        Region {
            start: u64::MAX,
            size_bytes: 1
        }
        .end(),
        u64::MAX
    );
    assert_eq!(
        Region {
            start: u64::MAX,
            size_bytes: u64::MAX
        }
        .end(),
        u64::MAX
    );
    // The ordinary case is unchanged.
    assert_eq!(
        Region {
            start: 0x4000_0000,
            size_bytes: 0x800_0000
        }
        .end(),
        0x4800_0000
    );
}

// ================================================================================================
// What a mutation run (cargo-mutants) proved this file was not yet checking. Every test below
// kills named survivors from a baseline run. The recurring finding: the suite parsed only trees
// with the DEFAULT cell widths (2/2 declared explicitly), so every walker's #address-cells
// handling, inheritance, and parent-vs-own-cells arithmetic was unexercised, and the header's
// boundary comparisons had never been met exactly.
// ================================================================================================

/// A copy of `blob` with one big-endian u32 overwritten at `off`.
fn patched(blob: &[u8], off: usize, val: u32) -> Vec<u8> {
    let mut b = blob.to_vec();
    b[off..off + 4].copy_from_slice(&val.to_be_bytes());
    b
}

/// One big-endian u32 cell, for `#address-cells = 1` layouts.
fn cell32(v: u32) -> Vec<u8> {
    v.to_be_bytes().to_vec()
}

fn minimal_tree() -> Vec<u8> {
    let mut b = Blob::new();
    b.begin_node(b"");
    b.prop(b"#address-cells", &2u32.to_be_bytes());
    b.prop(b"#size-cells", &2u32.to_be_bytes());
    b.end_node();
    b.finish()
}

/// The header comparisons, met exactly. The run showed `bytes.len() < total` could become `<=` or
/// `==` and `last_comp_version > 17` could become `>=` or `==`, because no test had ever handed
/// the parser a buffer of exactly `total` bytes, a buffer with slack, or a blob whose
/// `last_comp_version` was exactly 17; and each offset bound in the `||` chain had never been the
/// one that fired.
#[test]
fn the_header_boundaries_are_exact() {
    let blob = minimal_tree();
    let total = blob.len();

    // A buffer of exactly totalsize parses; slack after it is fine; one byte short is not.
    assert!(DeviceTreeBlob::from_bytes(&blob).is_ok());
    let mut slack = blob.clone();
    slack.extend_from_slice(&[0u8; 8]);
    let dt = DeviceTreeBlob::from_bytes(&slack).unwrap();
    assert_eq!(
        dt.total_size(),
        total,
        "the blob ends where its header says"
    );
    assert_eq!(
        DeviceTreeBlob::from_bytes(&blob[..total - 1]).err(),
        Some(Error::Truncated),
        "one byte short of totalsize"
    );

    // last_comp_version 17 is the newest we accept, and 18 is refused as itself.
    assert!(DeviceTreeBlob::from_bytes(&patched(&blob, 24, 17)).is_ok());
    assert_eq!(
        DeviceTreeBlob::from_bytes(&patched(&blob, 24, 18)).err(),
        Some(Error::UnsupportedVersion(18)),
    );

    // Each block offset alone can be the thing that is out of bounds.
    let t = total as u32;
    assert_eq!(
        DeviceTreeBlob::from_bytes(&patched(&blob, 8, t)).err(),
        Some(Error::Truncated)
    );
    assert_eq!(
        DeviceTreeBlob::from_bytes(&patched(&blob, 12, t)).err(),
        Some(Error::Truncated)
    );
    assert_eq!(
        DeviceTreeBlob::from_bytes(&patched(&blob, 16, t)).err(),
        Some(Error::Truncated)
    );
}

/// The reservation block, with entries in it. The fixtures' is empty, so `memory_reservations` could
/// return `Ok(0)` unconditionally, mis-stride the walk, or treat "starts at zero" as the
/// terminator (the `&&` in the all-zero check becoming `||`), and a reservation AT address zero
/// is exactly the entry firmware writes for its own vector table.
#[test]
fn reservations_are_read_entry_by_entry() {
    let mut b = Blob::new();
    b.begin_node(b"");
    // One prop, so the strings block is non-empty: an empty strings block puts off_strings at
    // exactly totalsize, which from_bytes rightly refuses.
    b.prop(b"#address-cells", &2u32.to_be_bytes());
    b.end_node();
    let blob = b.finish_with_reservations(&[(0, 0x1000), (0x8000_0000, 0x2000)]);
    let dt = DeviceTreeBlob::from_bytes(&blob).unwrap();

    let mut out = [Region {
        start: 0,
        size_bytes: 0,
    }; 4];
    assert_eq!(dt.memory_reservations(&mut out), Ok(2));
    assert_eq!((out[0].start, out[0].size_bytes), (0, 0x1000));
    assert_eq!((out[1].start, out[1].size_bytes), (0x8000_0000, 0x2000));

    // An entry that wraps the address space is refused, as a `reg` pair of that shape is, and one
    // that ends exactly at the top is not.
    let reservations = |entries: &[(u64, u64)]| {
        let mut b = Blob::new();
        b.begin_node(b"");
        b.prop(b"#address-cells", &2u32.to_be_bytes());
        b.end_node();
        b.finish_with_reservations(entries)
    };
    let blob = reservations(&[(0x1000, 0x1000), (u64::MAX - 0xfff, 0x1000)]);
    let dt = DeviceTreeBlob::from_bytes(&blob).unwrap();
    assert_eq!(dt.memory_reservations(&mut out), Err(Error::RegionOverflow));
    let blob = reservations(&[(u64::MAX - 0x1000, 0x1000)]);
    let dt = DeviceTreeBlob::from_bytes(&blob).unwrap();
    assert_eq!(dt.memory_reservations(&mut out), Ok(1));
}

/// `/memory` on a 32-bit-style board: `#address-cells = 1`, two reg entries. Deleting the
/// `#address-cells` match arm leaves the walker decoding with the 2-cell default, which misreads
/// every value; and the second entry is what catches a pair stride that multiplied where it
/// should have added.
#[test]
fn memory_with_one_address_cell() {
    let mut b = Blob::new();
    b.begin_node(b"");
    b.prop(b"#address-cells", &1u32.to_be_bytes());
    b.prop(b"#size-cells", &1u32.to_be_bytes());
    b.begin_node(b"memory@40000000");
    let mut reg = Vec::new();
    reg.extend(cell32(0x4000_0000));
    reg.extend(cell32(0x0100_0000));
    reg.extend(cell32(0x9000_0000));
    reg.extend(cell32(0x0010_0000));
    b.prop(b"device_type", b"memory\0");
    b.prop(b"reg", &reg);
    b.end_node();
    b.end_node();
    let blob = b.finish();
    let dt = DeviceTreeBlob::from_bytes(&blob).unwrap();

    let mut out = [Region {
        start: 0,
        size_bytes: 0,
    }; 4];
    assert_eq!(dt.memory_regions(&mut out), Ok(2));
    assert_eq!(
        (out[0].start, out[0].size_bytes),
        (0x4000_0000, 0x0100_0000)
    );
    assert_eq!(
        (out[1].start, out[1].size_bytes),
        (0x9000_0000, 0x0010_0000)
    );
}

/// Cell widths flow DOWN the tree and a node's own declaration applies to its CHILDREN, not to
/// its own `reg`. Three generations pin both rules: the bus inherits the root's 1/1 without
/// declaring anything (kills the inherit index becoming `depth / 1`), and the device declares
/// 2/2 for children it does not have, which must NOT apply to its own reg (kills the decode
/// index becoming `depth` instead of `depth - 1`).
#[test]
fn cell_widths_are_inherited_and_a_reg_uses_its_parents() {
    let mut b = Blob::new();
    b.begin_node(b"");
    b.prop(b"#address-cells", &1u32.to_be_bytes());
    b.prop(b"#size-cells", &1u32.to_be_bytes());
    b.begin_node(b"bus");
    b.begin_node(b"dev@10");
    b.prop(b"#address-cells", &2u32.to_be_bytes());
    b.prop(b"#size-cells", &2u32.to_be_bytes());
    let mut reg = Vec::new();
    reg.extend(cell32(0x1000_0000));
    reg.extend(cell32(0x100));
    reg.extend(cell32(0x2000_0000));
    reg.extend(cell32(0x200));
    b.prop(b"reg", &reg);
    b.end_node();
    b.end_node();
    b.end_node();
    let blob = b.finish();
    let dt = DeviceTreeBlob::from_bytes(&blob).unwrap();

    let mut out = [Region {
        start: 0,
        size_bytes: 0,
    }; 4];
    assert_eq!(dt.node_register_regions(b"dev@", &mut out), Ok(2));
    assert_eq!((out[0].start, out[0].size_bytes), (0x1000_0000, 0x100));
    assert_eq!((out[1].start, out[1].size_bytes), (0x2000_0000, 0x200));
}

