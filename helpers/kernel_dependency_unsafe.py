"""Every `unsafe` site in the registry crates the kernel links, regenerated from `Cargo.lock`.

§46 (thin primitives or whole subsystems; we write everything in between), in its kernel bar of
2026-10-25, asks each third-party crate the kernel links to list its hand-written `unsafe` and what
checks it. `notes/kernel-dependency-unsafe.md` is that listing's prose: what each site does, which
the kernel reaches, and what checks it upstream. This file keeps the counts and locations under it
current, so a bump that moves a crate's `unsafe` changes a checked-in table in the same pull request.

    python3 helpers/kernel_dependency_unsafe.py --write     # regenerate the table (runs cargo)
    python3 helpers/kernel_dependency_unsafe.py --check     # what script/lint runs: it is current
    python3 helpers/kernel_dependency_unsafe.py --summary   # counts per crate, from the table
    python3 helpers/kernel_dependency_unsafe.py --selftest  # the scanner, on fixture text

**Which crates.** `cargo tree -e normal -p kernel --target <t>` for each kernel target, keeping the
packages with no local path: the measure the bar's condition 3 names, so the two cannot disagree on
what the kernel links. Each crate is read where `cargo metadata` says its manifest is, which is the
registry's extracted copy of the exact version `Cargo.lock` pins. The downloaded source is only read.

**What counts as a site.** In the shipped source (every `.rs` outside `tests/`, `benches/`,
`examples/`, `fuzz/` and `build.rs`, the scope of `notes/dependency-standards-census/`), with comments
and literals blanked by `rust_source.strip_non_code`, each `unsafe` token is classified by what
follows it: a block, an `unsafe fn`, an `unsafe impl` (of `Send` or `Sync`, or of another unsafe
trait), an `unsafe trait`, or an `unsafe extern` block. Each `asm!`, `global_asm!` and `naked_asm!`
invocation is a site of its own, since inline assembly is unsafe code whether or not the `unsafe`
keyword sits on the same line. A site inside a `macro_rules!` body is marked with the macro's name,
because the bar counts what a crate's macros generate as the crate's own. Each invocation of such a
macro outside another macro's body is an `expansion` row, since that is where the generated unsafe
lands; a macro that only invokes another unsafe one counts as unsafe too. A site inside a
`#[cfg(test)]` module is marked, since no kernel build compiles it.

**Pinned facts.** `PINS` names facts in a crate's source that a nife claim rests on, such as the
orderings of `spin`'s lock. `--check` and `--write` both fail when one stops holding, so a bump
cannot regenerate its way past the claim.

**What this does not say.** It cannot tell which sites the kernel reaches, which `cfg` compiles
out, or what checks them; the note says each of those by hand, and a bump re-reads it.

Name: provisional (this file, the table and the note), minted 2026-10-25 UTC by the lane
maintainer/kernel-dependency-unsafe-listing.

BUGS

- Text, not a parser. A `macro_rules!` whose body names `unsafe` through a fragment
  (`$vis unsafe`) is found; one that builds the keyword some other way is not. Neither crate does
  that today.
- The function column is the nearest `fn` name above the site, which for a site in an `impl`
  block's associated constant or a closure is the function before it.
- An expansion is counted where the crate invokes its own macro. A macro the crate exports and a
  caller invokes is counted once, at its definition; the kernel invokes neither crate's macros
  that hold unsafe code.
"""
import json
import os
import pathlib
import re
import subprocess
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rust_source                                                          # noqa: E402

TABLE = pathlib.Path('notes/kernel-dependency-unsafe/sites.tsv')
KERNEL_TARGETS = ('aarch64-unknown-none-softfloat', 'riscv64imac-unknown-none-elf',
                  'x86_64-unknown-none')
NON_SHIPPED = ('tests/', 'benches/', 'examples/', 'fuzz/')

HEADER = """\
# Generated by `python3 helpers/kernel_dependency_unsafe.py --write`; `script/lint` fails when it
# is stale. Do not edit by hand. notes/kernel-dependency-unsafe.md says what each site is, which the
# kernel reaches and what checks it.
# targets: the kernel targets whose `cargo tree -e normal` includes the crate. path and line: in the
# crate's published source. kind: block, fn, impl-send-sync, impl-trait, trait, extern, asm, or
# expansion (an invocation of the crate's own macro whose expansion holds unsafe code).
# function: the `unsafe fn` itself, or the nearest `fn` above the site. macro: the `macro_rules!`
# whose body holds the site, or for an expansion the macro invoked; - for neither. test: yes for a
# site inside a `#[cfg(test)]` module, which no kernel build compiles.
crate\tversion\ttargets\tpath\tline\tkind\tfunction\tmacro\ttest
"""

# Facts about a pinned crate's source that a claim in nife rests on, checked on every `--check` and
# `--write`. Each is (crate, file, pattern, how many times it must match, the claim). A bump that
# changes one fails here even after the table is regenerated, because rereading the claim is the
# point. notes/kernel-dependency-unsafe.md lists them with the claims.
PINS = [
    ('spin', 'src/mutex/spin.rs',
     r'compare_exchange(?:_weak)?\(\s*false,\s*true,\s*Ordering::Acquire,\s*Ordering::Relaxed\s*\)',
     2, 'SpinMutex takes the lock with an Acquire compare-exchange, strong and weak '
        "(notes/memory-ordering.md, section 'Where this kernel's ordering actually lives')"),
    ('spin', 'src/mutex/spin.rs', r'\.store\(\s*false,\s*Ordering::Release\s*\)',
     2, 'SpinMutex releases the lock with a Release store, in the guard\'s drop and in '
        'force_unlock (notes/memory-ordering.md)'),
]

_UNSAFE = re.compile(r'\bunsafe\b')
_ASM = re.compile(r'\b(?:asm|global_asm|naked_asm)\s*!')
_FN = re.compile(r'\bfn\s+(\w+)')
_MACRO = re.compile(r'\bmacro_rules\s*!\s*(\w+)\s*[{(\[]')
_TEST_MOD = re.compile(r'#\[\s*cfg\s*\(\s*test\s*\)\s*\]\s*(?:#\[[^\]]*\]\s*)*'
                       r'(?:pub(?:\([^)]*\))?\s+)?mod\s+\w+\s*\{')
_AFTER = [
    (re.compile(r'\s*\{'), 'block'),
    (re.compile(r'(?:\s+extern\s+(?:"[^"]*"\s*)?)?\s+fn\s+(\w+)'), 'fn'),
    (re.compile(r'\s+impl\b[^{;]*?\b(?:Send|Sync)\s+for\b'), 'impl-send-sync'),
    (re.compile(r'\s+impl\b'), 'impl-trait'),
    (re.compile(r'\s+(?:auto\s+)?trait\b'), 'trait'),
    (re.compile(r'\s+extern\b'), 'extern'),
]
_CLOSE = {'{': '}', '(': ')', '[': ']'}


def _matching(code, i):
    """The index of the bracket that closes the one at `i`."""
    opener, depth = code[i], 0
    while i < len(code):
        if code[i] == opener:
            depth += 1
        elif code[i] == _CLOSE[opener]:
            depth -= 1
            if depth == 0:
                break
        i += 1
    return i


def macro_spans(code):
    """[(start, end, name)] of every `macro_rules!` body, by bracket matching on blanked code."""
    return [(m.start(), _matching(code, m.end() - 1), m.group(1)) for m in _MACRO.finditer(code)]


def test_spans(code):
    """[(start, end)] of every `#[cfg(test)]` module."""
    return [(m.start(), _matching(code, m.end() - 1)) for m in _TEST_MOD.finditer(code)]


def _within(spans, pos):
    return next((s[2] if len(s) > 2 else True for s in spans if s[0] <= pos <= s[1]), None)


def direct_sites(code):
    """[(pos, kind, unsafe fn name or None)] of the keyword and assembly sites in blanked code."""
    found = []
    for m in _UNSAFE.finditer(code):
        rest = code[m.end():m.end() + 400]
        hit = next(((pat.match(rest), k) for pat, k in _AFTER if pat.match(rest)), (None, None))
        # `other` is `unsafe` as a word the scanner does not know, such as a macro fragment
        # `$(unsafe)?`. Listed rather than dropped, so a new shape is seen.
        kind = hit[1] or 'other'
        found.append((m.start(), kind, hit[0].group(1) if kind == 'fn' else None))
    found += [(m.start(), 'asm', None) for m in _ASM.finditer(code)]
    return sorted(found)


def unsafe_macros(codes):
    """The crate's `macro_rules!` names whose expansion holds unsafe code, directly or through
    another of its macros."""
    bodies = {}
    for code in codes:
        for s, e, name in macro_spans(code):
            bodies.setdefault(name, []).append(code[s:e + 1])
    marked = {n for n, bs in bodies.items()
              if any(direct_sites(rust_source.strip_non_code(b)) for b in bs)}
    while True:
        more = {n for n, bs in bodies.items() if n not in marked
                and any(re.search(r'\b(?:' + '|'.join(map(re.escape, marked)) + r')\s*!', b)
                        for b in bs)} if marked else set()
        if not more:
            return marked
        marked |= more


def scan(text, macros=frozenset()):
    """[(line, kind, function, macro, test)] for one file's text. `macros` names the crate's
    unsafe-generating macros, whose invocations outside a macro body are listed as expansions."""
    code = rust_source.strip_non_code(text)
    spans, tests = macro_spans(code), test_spans(code)
    found = direct_sites(code)
    if macros:
        call = re.compile(r'\b(' + '|'.join(map(re.escape, sorted(macros))) + r')\s*!')
        found += [(m.start(), 'expansion', m.group(1)) for m in call.finditer(code)
                  if _within(spans, m.start()) is None and not
                  code[max(0, m.start() - 20):m.start()].rstrip().endswith('macro_rules!')]
    out = []
    for pos, kind, name in sorted(found):
        line = code.count('\n', 0, pos) + 1
        if kind == 'fn':
            fn = name
        else:
            fns = _FN.findall(code, 0, pos)
            fn = fns[-1] if fns else '-'
        macro = name if kind == 'expansion' else (_within(spans, pos) or '-')
        out.append((line, kind, fn, macro, 'yes' if _within(tests, pos) else '-'))
    return out


def shipped(rel):
    return rel.endswith('.rs') and not rel.startswith(NON_SHIPPED) and rel != 'build.rs'


def scan_tree(root):
    files = {}
    for path in sorted(pathlib.Path(root).rglob('*.rs')):
        rel = path.relative_to(root).as_posix()
        if shipped(rel):
            files[rel] = path.read_text(encoding='utf-8', errors='replace')
    macros = unsafe_macros(rust_source.strip_non_code(t) for t in files.values())
    return [(rel, *site) for rel, text in files.items() for site in scan(text, macros)]


def kernel_crates():
    """{(name, version): [targets]} for every non-path package the kernel links."""
    linked = {}
    for target in KERNEL_TARGETS:
        run = subprocess.run(['cargo', 'tree', '--locked', '-e', 'normal', '-p', 'kernel',
                              '--target', target, '--prefix', 'none', '--format', '{p}'],
                             capture_output=True, text=True)
        if run.returncode != 0:
            sys.exit(f'kernel_dependency_unsafe: cargo tree failed for {target}:\n{run.stderr}')
        for line in run.stdout.splitlines():
            line = line.replace(' (*)', '').strip()
            if not line or '(' in line:
                continue
            name, version = line.split(' ')
            targets = linked.setdefault((name, version.lstrip("v")), [])
            if target not in targets:
                targets.append(target)
    return linked


def source_dirs():
    run = subprocess.run(['cargo', 'metadata', '--locked', '--format-version', '1'],
                         capture_output=True, text=True)
    if run.returncode != 0:
        sys.exit(f'kernel_dependency_unsafe: cargo metadata failed:\n{run.stderr}')
    return {(p['name'], p['version']): pathlib.Path(p['manifest_path']).parent
            for p in json.loads(run.stdout)['packages'] if p['source']}


def check_pins(linked, dirs):
    """Fail when a pinned fact no longer holds in the source of a crate the kernel links."""
    versions = {name: version for name, version in linked}
    problems = []
    for name, rel, pattern, want, claim in PINS:
        if name not in versions:
            problems.append(f'  {name} is no longer linked by the kernel; drop its pin ({claim})')
            continue
        code = rust_source.strip_non_code((dirs[(name, versions[name])] / rel).read_text())
        got = len(re.findall(pattern, code))
        if got != want:
            problems.append(f'  {name} {versions[name]} {rel}: {got} matches of the pin for '
                            f'"{claim}", expected {want}')
    if problems:
        sys.exit('kernel_dependency_unsafe: a fact a nife claim rests on changed upstream:\n'
                 + '\n'.join(problems) + '\n  Reread the claim before changing the pin.')


def render(linked, dirs):
    lines = [HEADER]
    for (name, version), targets in sorted(linked.items()):
        short = ','.join(t.split('-')[0] for t in targets)
        for rel, line, kind, fn, macro, test in scan_tree(dirs[(name, version)]):
            lines.append(f'{name}\t{version}\t{short}\t{rel}\t{line}\t{kind}\t{fn}\t{macro}'
                         f'\t{test}\n')
    return ''.join(lines)


def summary(text):
    """Per crate: every site, then the hand-written ones a kernel build compiles (no test module,
    no expansion), split by kind."""
    counts = {}
    for row in text.splitlines():
        if row.startswith('#') or row.startswith('crate\t'):
            continue
        name, version, _t, _p, _l, kind, _f, macro, test = row.split('\t')
        c = counts.setdefault(f'{name} {version}', {'all': 0, 'test': 0, 'expansion': 0})
        c['all'] += 1
        if test == 'yes':
            c['test'] += 1
        elif kind == 'expansion':
            c['expansion'] += 1
        else:
            key = kind + (' in a macro body' if macro != '-' else '')
            c[key] = c.get(key, 0) + 1
    for crate, c in sorted(counts.items()):
        rest = {k: v for k, v in c.items() if k not in ('all', 'test', 'expansion')}
        print(f'{crate}: {c["all"]} rows; {sum(rest.values())} hand-written outside tests ('
              + ', '.join(f'{k} {v}' for k, v in sorted(rest.items()))
              + f'); {c["expansion"]} macro expansions; {c["test"]} in test modules')


def selftest():
    text = '''
// unsafe { not code }
macro_rules! m { () => { unsafe { 1 } }; }
macro_rules! n { () => { m!() }; }
fn a() { let s = "unsafe {"; unsafe { core::arch::asm!("nop") } }
unsafe fn b() {}
pub unsafe extern "C" fn c() {}
unsafe impl Send for T {}
unsafe impl GlobalAlloc for T {}
unsafe trait U {}
n!();
#[cfg(test)]
mod tests { fn t() { unsafe { 2 } } }
'''
    code = rust_source.strip_non_code(text)
    macros = unsafe_macros([code])
    got = [(k, f, m, t) for _l, k, f, m, t in scan(text, macros)]
    want = [('block', '-', 'm', '-'), ('block', 'a', '-', '-'), ('asm', 'a', '-', '-'),
            ('fn', 'b', '-', '-'), ('fn', 'c', '-', '-'), ('impl-send-sync', 'c', '-', '-'),
            ('impl-trait', 'c', '-', '-'), ('trait', 'c', '-', '-'),
            ('expansion', 'c', 'n', '-'), ('block', 't', '-', 'yes')]
    if macros != {'m', 'n'} or got != want:
        sys.exit(f'kernel_dependency_unsafe: selftest failed\n  macros {macros}\n'
                 f'  got  {got}\n  want {want}')


def main():
    arg = sys.argv[1] if len(sys.argv) > 1 else ''
    if arg == '--selftest':
        selftest()
    elif arg == '--summary':
        summary(TABLE.read_text())
    elif arg in ('--write', '--check'):
        linked, dirs = kernel_crates(), source_dirs()
        check_pins(linked, dirs)
        text = render(linked, dirs)
        if arg == '--write':
            TABLE.parent.mkdir(parents=True, exist_ok=True)
            TABLE.write_text(text)
        elif not TABLE.exists() or TABLE.read_text() != text:
            sys.exit(f'kernel_dependency_unsafe: {TABLE} is stale. A crate the kernel links changed '
                     'version or set; run `python3 helpers/kernel_dependency_unsafe.py --write`, then '
                     're-read each changed site against notes/kernel-dependency-unsafe.md')
    else:
        sys.exit(__doc__.split('\n\n')[1])


if __name__ == '__main__':
    main()
