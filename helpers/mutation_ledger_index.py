"""Generate the crate-to-file table in notes/mutation-testing/README.md.

The mutation ledgers under notes/mutation-testing/ are cut into many files, so finding one crate's
survivors can mean scanning several. This script reads them and writes one row per crate: which
files hold a section headed by the crate, which hold a table row for it, and how many rows the
machine-read triage file has for it.

    python3 helpers/mutation_ledger_index.py write     # regenerate the table in the README
    python3 helpers/mutation_ledger_index.py check     # fail when the README differs from a regeneration
    python3 helpers/mutation_ledger_index.py --selftest

A heading names a crate when the crate is in backticks, or when the whole heading is a plain list of
identifiers ("ps, pgrep, pmap"; a trailing count in parentheses is ignored). A table row names a
crate when its first cell is the crate in backticks. Older names resolve to the current one through
notes/project-metrics/mutation-census-renames.csv, and the older names are listed beside it. The
table sits between the two marker comments in the README; nothing else in the README is touched.
The ledgers are never moved or renamed by this script.

Name: provisional, minted by the lane that wrote the index; naming is an architect's.
"""
import collections
import csv
import pathlib
import re
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
BEGIN = "<!-- crate-table:begin (generated by helpers/mutation_ledger_index.py) -->"
END = "<!-- crate-table:end -->"
# Files that are not ledgers of one census or run: the README itself, and the generated per-crate
# classification, which would otherwise list every crate.
SKIP = {"README.md", "survivor-classification.md"}
PLAIN = re.compile(r"^[a-z][a-z0-9_]*((, | and )[a-z][a-z0-9_]*)*( \(.*\))?$")
IDENT = re.compile(r"[a-z][a-z0-9_]*")


def slug(heading):
    s = heading.strip().lower().replace("`", "")
    s = re.sub(r"[^a-z0-9 _-]", "", s)
    return s.replace(" ", "-")


def heading_names(text):
    """The identifiers a heading names: backticked ones, or all of a plain list."""
    ticked = re.findall(r"`([a-z][a-z0-9_]*)`", text)
    if ticked:
        return ticked
    if PLAIN.match(text):
        return IDENT.findall(re.sub(r"\(.*\)", "", text))
    return []


def load_renames(path):
    chain = {}
    if path.exists():
        for row in csv.DictReader(path.open()):
            chain[row["old"]] = row["new"]
    return chain


def resolve(name, chain):
    seen = set()
    while name in chain and name not in seen:
        seen.add(name)
        name = chain[name]
    return name


def scan_markdown(path, chain):
    """Yield (current name, kind, anchor) for each heading or first-cell table row naming a crate."""
    anchor = ""
    for line in path.read_text().splitlines():
        m = re.match(r"^(#{1,6}) (.*)$", line)
        if m and len(m.group(1)) == 1:
            continue  # a file title names its scope, not a section
        if m:
            anchor = slug(m.group(2))
            for n in heading_names(m.group(2)):
                yield resolve(n, chain), "section", anchor
            continue
        m = re.match(r"^\| `([a-z][a-z0-9_]*)` \|", line)
        if m:
            yield resolve(m.group(1), chain), "row", anchor


def known_names(root, chain, triage):
    names = set(chain) | set(chain.values()) | set(triage)
    crates = root / "crates"
    if crates.is_dir():
        names |= {p.name for p in crates.iterdir() if p.is_dir()}
    return names


def triage_counts(path, chain):
    counts = collections.Counter()
    if path.exists():
        for row in csv.DictReader(path.open()):
            counts[resolve(row["crate"].split("::")[-1], chain)] += 1
    return counts


def build(root):
    chain = load_renames(root / "notes/project-metrics/mutation-census-renames.csv")
    counts = triage_counts(root / "notes/project-metrics/mutation-triage.csv", chain)
    known = {resolve(n, chain) for n in known_names(root, chain, counts)}
    refs = collections.defaultdict(list)  # name -> [(file, kind, anchor)]
    ledgers = root / "notes/mutation-testing"
    for path in sorted(ledgers.glob("*.md")):
        if path.name in SKIP:
            continue
        seen = set()
        for name, kind, anchor in scan_markdown(path, chain):
            if name in known and (name, kind) not in seen:
                seen.add((name, kind))
                refs[name].append((path.name, kind, anchor))
    old = collections.defaultdict(list)
    for o in chain:
        old[resolve(o, chain)].append(o)
    rows = []
    for name in sorted(set(refs) | set(counts)):
        links = []
        for f, kind, anchor in refs.get(name, []):
            label = f[:-3] + (" (row)" if kind == "row" else "")
            links.append(f"[{label}]({f}#{anchor})" if anchor else f"[{label}]({f})")
        was = ", ".join(f"`{o}`" for o in sorted(old.get(name, [])))
        rows.append(f"| `{name}` | {was} | {'<br>'.join(links) or 'triage file only'} | {counts.get(name, 0)} |")
    head = ["| crate | earlier names | ledger sections and rows | rows in the triage file |",
            "|---|---|---|---|"]
    return "\n".join([BEGIN, ""] + head + rows + ["", END])


def splice(readme, table):
    if BEGIN not in readme or END not in readme:
        return None
    a = readme.index(BEGIN)
    b = readme.index(END) + len(END)
    return readme[:a] + table + readme[b:]


def run(root, mode):
    readme = root / "notes/mutation-testing/README.md"
    new = splice(readme.read_text(), build(root))
    if new is None:
        print("mutation_ledger_index: the README has no crate-table markers", file=sys.stderr)
        return 2
    if mode == "write":
        readme.write_text(new)
        return 0
    if new != readme.read_text():
        print("mutation_ledger_index: the README table is stale; run "
              "python3 helpers/mutation_ledger_index.py write", file=sys.stderr)
        return 1
    return 0


def selftest():
    with tempfile.TemporaryDirectory() as d:
        root = pathlib.Path(d)
        (root / "notes/project-metrics").mkdir(parents=True)
        (root / "notes/mutation-testing").mkdir(parents=True)
        (root / "crates/alpha").mkdir(parents=True)
        (root / "notes/project-metrics/mutation-census-renames.csv").write_text(
            "old,new,commit,date\nold_alpha,alpha,x,y\n")
        (root / "notes/project-metrics/mutation-triage.csv").write_text(
            "crate,function,mutation,disposition,reason\nalpha,f,m,killed,r\n"
            "driver::beta,f,m,killed,r\n")
        (root / "notes/mutation-testing/one.md").write_text(
            "# Title about `alpha`\n\n### `old_alpha` (3)\n\ntext\n\n## beta, alpha\n\n"
            "## Prose heading with alpha in it\n")
        (root / "notes/mutation-testing/two.md").write_text(
            "## The rows\n\n| crate | n |\n|---|---|\n| `alpha` | 1 |\n| `gamma` | 2 |\n")
        (root / "notes/mutation-testing/README.md").write_text(f"intro\n{BEGIN}\nold\n{END}\ntail\n")
        t = build(root)
        assert "| `alpha` | `old_alpha` | [one](one.md#old_alpha-3)<br>[two (row)](two.md#the-rows) | 1 |" in t, t
        assert "| `beta` |  | [one](one.md#beta-alpha) | 1 |" in t, t
        assert "gamma" not in t and "Prose" not in t, t
        assert run(root, "check") == 1
        assert run(root, "write") == 0
        assert run(root, "check") == 0
        assert (root / "notes/mutation-testing/README.md").read_text().startswith("intro\n")
        assert (root / "notes/mutation-testing/README.md").read_text().endswith("tail\n")
    print("mutation_ledger_index selftest ok")
    return 0


if __name__ == "__main__":
    if sys.argv[1:] == ["--selftest"]:
        sys.exit(selftest())
    if len(sys.argv) == 2 and sys.argv[1] in ("write", "check"):
        sys.exit(run(ROOT, sys.argv[1]))
    print(__doc__)
    sys.exit(2)
