"""Which side of the trust boundary links each `crates/` member, derived from `cargo metadata`.

`rust_source.trust_bucket` splits the unsafe census by what confines the code (milestone 522 (a
boundary drawn by dependency, not by path)). For a `crates/` member the answer is which binaries
link it, and that is a dependency-graph fact. `script/metrics` cannot run cargo (its own header),
so the answer is written to `helpers/trust_boundary_crates.tsv`, checked in, and read from there.
This file writes it and checks it.

    python3 helpers/trust_boundary.py --write      # regenerate the table (runs cargo metadata)
    python3 helpers/trust_boundary.py --check      # what script/lint runs: the table is current
    python3 helpers/trust_boundary.py --check-rows # no cargo: every crates/ member has one row
    python3 helpers/trust_boundary.py --selftest   # the rule, on fixture graphs

**The rule.** A crate is `kernel` when a kernel root reaches it, `userspace` when a userspace root
does, `shared` when both do, `boot_chain` when only `uefi_loader` does, and `host` when no binary
that runs on nife links it. Reaching means a path of normal dependency edges. A `dev` edge links
only a test binary, and a `build` edge links a build script, which runs on the developer's machine.
Features are all on (`--all-features`), so a crate any kernel build can link counts on the kernel
side, a bench or test image included: this split may overstate what the kernel trusts but never
hides kernel-privileged code in a userspace count.

Userspace has three kinds of root: the `components` and `fixtures` packages; each directory in
`rust_source.USERSPACE_ONLY_DIRS` that is its own cargo workspace (outside the root one, so
`cargo metadata` at the root never sees it); and the crates `cargo xtask std-src` copies verbatim
into nife's `std`, which no manifest names, read from `STD_GENERATOR`'s `root.join(...)` lines.

`system_tests` is not a root. It is a test image that links the kernel, its own source is outside
this split (`rust_source.trust_bucket`'s BUGS), and a crate only it reaches is `host` here.

Name: provisional (this file and the table), minted 2026-10-20 UTC by the lane
maintainer/unsafe-trust-unclassified.

BUGS

- `--all-features` unions every feature of every package. A crate behind a kernel feature that no
  shipped or tested kernel build enables would still count as `kernel`. None does today.
"""
import json
import os
import pathlib
import re
import subprocess
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rust_source                                                          # noqa: E402

TABLE = pathlib.Path(__file__).with_name('trust_boundary_crates.tsv')
KERNEL_ROOTS = ('kernel',)
USERSPACE_ROOTS = ('components', 'fixtures')
BOOT_CHAIN_ROOTS = ('uefi_loader',)
STD_GENERATOR = 'xtask/src/farm/generate.rs'
STD_ROOT = 'std'
_STD_COPY = re.compile(r'root\.join\("crates/([a-z0-9_]+)/src/lib\.rs"\)')
# Workspaces of their own that never run on nife. Any other top-level directory with a
# `[workspace]` table must be in `rust_source.USERSPACE_ONLY_DIRS`, or `--check-rows` fails: a new
# one would otherwise be a root this derivation never reads.
HOST_WORKSPACES = ('fuzz',)

HEADER = """\
# Generated by `python3 helpers/trust_boundary.py --write`; `script/lint` fails when it is stale.
# Do not edit by hand. The rule is in helpers/trust_boundary.py's docstring.
# crate: a crates/ directory. bucket: kernel, userspace, shared, boot_chain or host.
# linked_by: the roots that reach it over normal edges, - for none, or retired for a crate no
# longer in the tree. --write keeps a retired row with the side it last derived, so script/metrics
# can still place that crate's unsafe in the historical weeks that held it.
crate\tbucket\tlinked_by
"""


def userspace_workspaces():
    return [d.rstrip('/') for d in rust_source.USERSPACE_ONLY_DIRS if os.path.isdir(d)]


def cargo_metadata(manifest, *flags):
    run = subprocess.run(['cargo', 'metadata', '--format-version', '1', *flags,
                          '--manifest-path', manifest], capture_output=True, text=True)
    if run.returncode != 0:
        sys.exit(f'trust_boundary: cargo metadata failed for {manifest}:\n{run.stderr}')
    return json.loads(run.stdout)


def crate_dir(manifest_path, root):
    """The `crates/<dir>` a manifest belongs to, or `None` for a package outside `crates/`."""
    parent = pathlib.Path(manifest_path).parent
    if not parent.is_relative_to(root):
        return None
    parts = parent.relative_to(root).parts
    return parts[1] if len(parts) == 2 and parts[0] == 'crates' else None


def path_deps(meta, root):
    """The `crates/` directories a workspace's own members name as normal path dependencies.

    Read from `--no-deps` metadata, which declares edges without resolving them: a workspace of
    its own may commit no `Cargo.lock` (`entropy_backend` does not), and resolving one would
    write it or need the network. Every optional dependency counts, as `--all-features` would.
    The walk onward from these crates is the root graph's.
    """
    return {d for pkg in meta['packages'] if pkg['id'] in meta['workspace_members']
            for dep in pkg['dependencies'] if dep['kind'] is None and dep.get('path')
            for d in [crate_dir(pathlib.Path(dep['path']) / 'Cargo.toml', root)] if d}


def reached(meta, root, starts):
    """The `crates/` directories a normal-edge walk reaches from `starts`, a set of root-workspace
    package names or `crates/` directories."""
    by_id = {p['id']: p for p in meta['packages']}
    edges = {n['id']: [d['pkg'] for d in n.get('deps', [])
                       if any(k['kind'] is None for k in d['dep_kinds'])]
             for n in meta['resolve']['nodes']}
    stack = [i for i in meta['workspace_members']
             if by_id[i]['name'] in starts or crate_dir(by_id[i]['manifest_path'], root) in starts]
    seen = set()
    while stack:
        pid = stack.pop()
        if pid not in seen:
            seen.add(pid)
            stack.extend(edges.get(pid, []))
    return {d for d in (crate_dir(by_id[i]['manifest_path'], root) for i in seen) if d}


def classify(root_meta, root, workspace_seeds, std_copied):
    """{crate dir: (bucket, linked_by)} for every `crates/` member of the root workspace.

    `workspace_seeds` is {workspace dir name: the crates/ dirs it names}; `std_copied` the crate
    dirs copied into `std`.
    """
    linked = {}
    seeds = {name: {name} for name in KERNEL_ROOTS + USERSPACE_ROOTS + BOOT_CHAIN_ROOTS}
    seeds.update(workspace_seeds)
    seeds[STD_ROOT] = set(std_copied)
    for name, starts in seeds.items():
        for d in reached(root_meta, root, starts):
            linked.setdefault(d, set()).add(name)

    userspace = set(USERSPACE_ROOTS) | set(workspace_seeds) | {STD_ROOT}
    by_id = {p['id']: p for p in root_meta['packages']}
    out = {}
    for pid in root_meta['workspace_members']:
        d = crate_dir(by_id[pid]['manifest_path'], root)
        if d is None:
            continue
        roots = linked.get(d, set())
        k, u = bool(roots & set(KERNEL_ROOTS)), bool(roots & userspace)
        bucket = ('shared' if k and u else 'kernel' if k else 'userspace' if u
                  else 'boot_chain' if roots & set(BOOT_CHAIN_ROOTS) else 'host')
        out[d] = (bucket, ','.join(sorted(roots)) or '-')
    return out


def derive():
    root = pathlib.Path.cwd().resolve()
    seeds = {w: path_deps(cargo_metadata(f'{w}/Cargo.toml', '--no-deps'), root)
             for w in userspace_workspaces()}
    std_copied = set(_STD_COPY.findall(pathlib.Path(STD_GENERATOR).read_text()))
    if not std_copied:
        sys.exit(f'trust_boundary: no crate copied into std found in {STD_GENERATOR}; '
                 'its root.join(...) lines changed shape, so this derivation must follow them')
    root_meta = cargo_metadata('Cargo.toml', '--locked', '--all-features')
    return classify(root_meta, root, seeds, std_copied)


RETIRED = 'retired'


def with_retired(table, path=TABLE):
    """`table` plus a retired row for every crate the checked-in file names and the tree no
    longer has, carrying the side the file last gave it."""
    out = dict(table)
    for crate, (bucket, _linked_by) in read_rows(path).items():
        out.setdefault(crate, (bucket, RETIRED))
    return out


def render(table):
    return HEADER + ''.join(f'{c}\t{b}\t{r}\n' for c, (b, r) in sorted(table.items()))


def read_rows(path=TABLE):
    """{crate dir: (bucket, linked_by)} from the checked-in table."""
    rows = {}
    for line in path.read_text().splitlines():
        if line.startswith('#') or line.startswith('crate\t'):
            continue
        crate, bucket, linked_by = line.split('\t')
        rows[crate] = (bucket, linked_by)
    return rows


def check_rows():
    """No cargo: the table has exactly one row per `crates/*/Cargo.toml`, and every workspace of
    its own is a userspace root or named in `HOST_WORKSPACES`. The pre-push hook runs this."""
    members = {p.parent.name for p in pathlib.Path('crates').glob('*/Cargo.toml')}
    rows = read_rows()
    live = {c for c, (_b, linked_by) in rows.items() if linked_by != RETIRED}
    problems = [f'  crates/{c} has no row' for c in sorted(members - live)]
    problems += [f'  {c} has a row but no crates/{c}/Cargo.toml' for c in sorted(live - members)]
    known = {w.rstrip('/') for w in rust_source.USERSPACE_ONLY_DIRS} | set(HOST_WORKSPACES)
    for manifest in sorted(pathlib.Path('.').glob('*/Cargo.toml')):
        if re.search(r'^\[workspace\]', manifest.read_text(), re.M) and \
                manifest.parent.name not in known:
            problems.append(f'  {manifest.parent}/ is a workspace of its own and neither '
                            'rust_source.USERSPACE_ONLY_DIRS nor HOST_WORKSPACES names it')
    if problems:
        sys.exit(f'trust_boundary: {TABLE.name} does not cover the tree:\n' + '\n'.join(problems)
                 + '\nrun `python3 helpers/trust_boundary.py --write` (it runs cargo metadata)')
    print(f'trust boundary: {len(live)} crates/ members, one row each')


def check():
    want = render(with_retired(derive()))
    if TABLE.read_text() != want:
        have = TABLE.read_text().splitlines()
        diff = [f'  - {line}' for line in have if line not in want.splitlines()]
        diff += [f'  + {line}' for line in want.splitlines() if line not in have]
        sys.exit(f'trust_boundary: {TABLE.name} disagrees with cargo metadata:\n'
                 + '\n'.join(diff) + '\nrun `python3 helpers/trust_boundary.py --write`')
    print(f'trust boundary: {TABLE.name} matches cargo metadata')


def selftest():
    """The rule's edges, on a fixture graph: each case is a way a crate could land on the wrong
    side of the boundary that the real graph does not exhibit today."""
    root = pathlib.Path('/r')

    def pkg(name, where):
        return {'id': name, 'name': name, 'manifest_path': f'/r/{where}/Cargo.toml'}

    def dep(name, *kinds):
        return {'pkg': name, 'dep_kinds': [{'kind': k, 'target': None} for k in kinds]}

    names = ['kernel', 'components', 'fixtures', 'uefi_loader', 'xtask']
    crates = ['normal', 'dev_only', 'build_only', 'both_sides', 'via_build', 'loader', 'tool',
              'workspace_only', 'std_only']
    meta = {
        'packages': [pkg(n, n) for n in names] + [pkg(c, f'crates/{c}') for c in crates],
        'workspace_members': names + crates,
        'resolve': {'nodes': [
            {'id': 'kernel', 'deps': [dep('normal', None), dep('dev_only', 'dev'),
                                      dep('build_only', 'build'), dep('both_sides', None)]},
            {'id': 'components', 'deps': [dep('both_sides', None)]},
            {'id': 'build_only', 'deps': [dep('via_build', None)]},
            {'id': 'uefi_loader', 'deps': [dep('loader', None)]},
            {'id': 'xtask', 'deps': [dep('tool', None)]},
        ] + [{'id': n, 'deps': []} for n in crates]},
    }
    other = {'packages': [{'id': 'server', 'dependencies': [
                 {'kind': None, 'path': '/r/crates/workspace_only'},
                 {'kind': 'dev', 'path': '/r/crates/dev_only'},
                 {'kind': None, 'path': '/r/vendor/thing'}]}],
             'workspace_members': ['server']}
    got = {c: b for c, (b, _r) in
           classify(meta, root, {'server': path_deps(other, root)}, {'std_only'}).items()}
    want = {'normal': 'kernel', 'dev_only': 'host', 'build_only': 'host', 'via_build': 'host',
            'both_sides': 'shared', 'loader': 'boot_chain', 'tool': 'host',
            'workspace_only': 'userspace', 'std_only': 'userspace'}
    if got != want:
        sys.exit('trust_boundary selftest failed:\n'
                 + '\n'.join(f'  {c}: got {got.get(c)}, want {want[c]}'
                             for c in sorted(want) if got.get(c) != want[c]))
    print(f'trust boundary selftest: {len(want)} cases')


if __name__ == '__main__':
    modes = {'--write': lambda: TABLE.write_text(render(with_retired(derive()))), '--check': check,
             '--check-rows': check_rows, '--selftest': selftest}
    if len(sys.argv) != 2 or sys.argv[1] not in modes:
        sys.exit(f'usage: {sys.argv[0]} ' + '|'.join(modes))
    modes[sys.argv[1]]()
